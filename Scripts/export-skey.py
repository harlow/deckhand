#!/usr/bin/env python3
"""Export S-KEY (Deezer, MIT; github.com/deezer/skey) for Deckhand.

Writes:
  Sources/Analysis/SKeyConstants.swift            CQT filter constants (nnAudio VQT buffers)
  Sources/Analysis/Resources/SKeyChromaNet.mlmodelc  ChromaNet compiled for Core ML

The CQT front-end is reimplemented in Swift (SKeyCQT.swift) from the same buffers; ChromaNet runs in
Core ML on fixed 15 s clips (84 bins x 646 frames at 22.05 kHz, hop 512).

Usage: python3 Scripts/export-skey.py <path to deezer/skey checkout> [fine-tuned checkpoint.pt]
  The optional checkpoint ({"chromanet": state_dict}) replaces ChromaNet's weights; the CQT front-end
  is always S-KEY's.
Needs: torch, nnAudio, einops, coremltools (macOS for compiling).
"""
import os, subprocess, sys, tempfile
import numpy as np
import torch
import torch.nn.functional as F

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, sys.argv[1])
from skey.key_detection import load_checkpoint, load_model_components  # noqa: E402

hcqt, net, _ = load_model_components(load_checkpoint(None), torch.device("cpu"))
if len(sys.argv) > 2:
    net.load_state_dict(torch.load(sys.argv[2], map_location="cpu")["chromanet"])
for p in net.parameters():
    p.requires_grad_(False)

# --- CQT constants -------------------------------------------------------------------------------
assert hcqt.hop_length == 512 and hcqt.n_octaves == 9 and not hcqt.earlydownsample
kr = hcqt.cqt_kernels_real_0.numpy()[:, 0, :]
ki = hcqt.cqt_kernels_imag_0.numpy()[:, 0, :]
assert all(torch.equal(getattr(hcqt, f"cqt_kernels_real_{i}"), hcqt.cqt_kernels_real_0) for i in range(9))


def arr(v):
    return "[" + ", ".join(f"{float(x):.9g}" for x in np.ravel(v)) + "]"


with open(os.path.join(ROOT, "Sources/Analysis/SKeyConstants.swift"), "w") as f:
    f.write(f"""// Generated by Scripts/export-skey.py from S-KEY's nnAudio VQT (MIT). Do not edit by hand.
enum SKeyConstants {{
    /// 256-tap low-pass used to halve the sample rate between octaves.
    static let lowpass: [Float] = {arr(hcqt.lowpass_filter.numpy())}
    /// 12 complex CQT kernels x 128 taps (top octave), row-major; reused for every octave.
    static let kernelsReal: [Float] = {arr(kr)}
    static let kernelsImag: [Float] = {arr(ki)}
    /// Filter length per bin (99 bins from 27.5 Hz), for librosa-style normalization.
    static let lengths: [Float] = {arr(hcqt.lenghts.numpy())}
}}
""")

# --- ChromaNet -> Core ML ------------------------------------------------------------------------
def static_norm(x, _shape):  # F.layer_norm(x, x.shape[1:]) without a traced shape
    m = x.mean((1, 2, 3), keepdim=True)
    v = ((x - m) ** 2).mean((1, 2, 3), keepdim=True)
    return (x - m) / torch.sqrt(v + 1e-5)


class ReplicateConv(torch.nn.Module):  # the converter drops Conv2d(padding_mode="replicate")
    def __init__(self, conv):
        super().__init__()
        ph, pw = conv.padding
        self.pad = (pw, pw, ph, ph)
        self.conv = torch.nn.Conv2d(conv.in_channels, conv.out_channels, conv.kernel_size, padding=0, groups=conv.groups)
        self.conv.load_state_dict(conv.state_dict())

    def forward(self, x):
        return self.conv(F.pad(x, self.pad, mode="replicate"))


for blk in list(net.convnext_blocks) + list(net.time_downsampling_blocks):
    blk.norm = static_norm
for blk in net.convnext_blocks:
    blk.dwconv = ReplicateConv(blk.dwconv)


class ChromaNetFixed(torch.nn.Module):
    """ChromaNet.forward with constant shapes; output = 24 probabilities in S-KEY's key_map order."""
    def __init__(self):
        super().__init__()
        self.net = net

    def forward(self, x):
        n = self.net
        for cb, tb in zip(n.convnext_blocks, n.time_downsampling_blocks):
            x = cb(tb(x))
        x = sum(x[:, :, 12 * j:12 * (j + 1), :] for j in range(7)) / 7
        x = n.batch_norm(n.classifier(x.mean(3, keepdim=True))).reshape(1, 24)
        return torch.softmax(x / n.temperature, dim=-1)


import coremltools as ct  # noqa: E402

example = torch.rand(1, 1, 84, 646)
model = ChromaNetFixed().eval()
with torch.no_grad():
    assert torch.allclose(model(example), net(example), atol=1e-5)
    traced = torch.jit.trace(model, example)
ml = ct.convert(traced, inputs=[ct.TensorType(name="cqt", shape=(1, 1, 84, 646))], outputs=[ct.TensorType(name="probs")],
                minimum_deployment_target=ct.target.macOS14, compute_precision=ct.precision.FLOAT32)
ml.short_description = "S-KEY ChromaNet (Kong et al., ICASSP 2025; Deezer, MIT): 15 s log-CQT -> 24 key probabilities"
with tempfile.TemporaryDirectory() as tmp:
    pkg = os.path.join(tmp, "SKeyChromaNet.mlpackage")
    ml.save(pkg)
    out = os.path.join(ROOT, "Sources/Analysis/Resources")
    os.makedirs(out, exist_ok=True)
    subprocess.run(["rm", "-rf", os.path.join(out, "SKeyChromaNet.mlmodelc")], check=True)
    subprocess.run(["xcrun", "coremlcompiler", "compile", pkg, out], check=True, stdout=subprocess.DEVNULL)
print("wrote SKeyConstants.swift and Resources/SKeyChromaNet.mlmodelc")
