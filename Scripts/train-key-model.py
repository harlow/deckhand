#!/usr/bin/env python3
"""Train Deckhand's key model and regenerate Sources/Analysis/KeyModelWeights.swift.

1. Dump features (chromagrams via the shipping KeyAnalyzer.chromagram path + tag keys):
     swift build -c release --product deckhand-eval
     .build/release/deckhand-eval key-features ~/Music/Music/Media.localized/Music /tmp/keyfeat
2. Optionally export Mixed In Key confidences (path, conf) to JSON for per-confidence reporting.
3. python3 Scripts/train-key-model.py /tmp/keyfeat [mik.json]   (needs numpy, scipy)

Model: one linear weight vector per mode over the 72-band √-mean chroma, applied to the chroma
rotated to each of 12 candidate tonics (rotation-equivariant multinomial logistic regression).
Held-out split: album folders whose MD5 ≡ 0 (mod 5). The shipped model is trained on all tracks.
"""
import hashlib, json, os, sys
import numpy as np
from scipy.optimize import minimize

SCALE, L2 = 30, 1e-3
OUT = os.path.join(os.path.dirname(__file__), "..", "Sources", "Analysis", "KeyModelWeights.swift")

def camelot(s):
    n, minor = int(s[:-1]), s[-1] == "A"
    rel = ((n - 8) % 12) * 7 % 12
    return (rel + 9) % 12 if minor else rel, minor

def label(s):
    t, m = camelot(s)
    return t * 2 + int(m)

def relation(p, t):
    (pt, pm), (tt, tm) = divmod(p, 2), divmod(t, 2)
    if p == t: return "exact"
    if pm != tm and ((not tm and pt == (tt + 9) % 12) or (tm and pt == (tt + 3) % 12)): return "relative"
    if pm == tm and (pt - tt) % 12 in (5, 7): return "fifth"
    if pm != tm and pt == tt: return "parallel"
    return "other"

WEIGHT = {"exact": 1, "fifth": .5, "relative": .3, "parallel": .2, "other": 0}

def report(name, pred, truth):
    rel = [relation(p, t) for p, t in zip(pred, truth)]
    n = len(rel)
    cols = " ".join(f"{k} {100 * rel.count(k) / n:5.1f}" for k in WEIGHT)
    print(f"{name:14s} n={n:4d} {cols}  MIREX {100 * sum(WEIGHT[r] for r in rel) / n:5.1f}")

def features(root, entries):
    X = []
    for e in entries:
        a = np.fromfile(f"{root}/{e['i']}.f32", dtype=np.float32).reshape(-1, 72).astype(np.float64)
        v = np.sqrt(a).mean(0)
        X.append(v / (np.linalg.norm(v) + 1e-12) * SCALE)
    return np.array(X)

def rotations(X):
    return np.stack([np.roll(X, -k, axis=1) for k in range(12)], 1)

def fit(R, y):
    n = len(y)
    Y = np.zeros((n, 24)); Y[np.arange(n), y] = 1
    def loss(th):
        W, b = th[:144].reshape(2, 72), th[144:]
        S = (np.einsum("nkd,md->nkm", R, W) + b).reshape(n, 24)
        S -= S.max(1, keepdims=True); P = np.exp(S); P /= P.sum(1, keepdims=True)
        G = ((P - Y) / n).reshape(n, 12, 2)
        L = -np.log(P[np.arange(n), y] + 1e-12).mean() + 0.5 * L2 * (W ** 2).sum()
        return L, np.concatenate([(np.einsum("nkm,nkd->md", G, R) + L2 * W).ravel(), G.sum((0, 1))])
    th = minimize(loss, np.zeros(146), jac=True, method="L-BFGS-B", options={"maxiter": 1000}).x
    return th[:144].reshape(2, 72), th[144:]

def predict(R, W, b):
    return list((np.einsum("nkd,md->nkm", R, W) + b).reshape(len(R), 24).argmax(1))

def held(e):
    return int(hashlib.md5(os.path.dirname(e["path"]).encode()).hexdigest(), 16) % 5 == 0

def main():
    root = sys.argv[1]
    entries = json.load(open(f"{root}/index.json"))
    conf = {}
    if len(sys.argv) > 2:
        conf = {m["path"]: m["conf"] for m in json.load(open(sys.argv[2]))}
    train = [e for e in entries if not held(e)]
    test = [e for e in entries if held(e)]
    W, b = fit(rotations(features(root, train)), np.array([label(e["tag"]) for e in train]))
    pred = predict(rotations(features(root, test)), W, b)
    truth = [label(e["tag"]) for e in test]
    report("held-out", pred, truth)
    if conf:
        for name, keep in [("conf>=0.8", lambda c: c >= 0.8), ("conf<0.5", lambda c: c < 0.5)]:
            sel = [i for i, e in enumerate(test) if keep(conf.get(e["path"], 0.5))]
            report(name, [pred[i] for i in sel], [truth[i] for i in sel])

    W, b = fit(rotations(features(root, entries)), np.array([label(e["tag"]) for e in entries]))
    row = lambda v: "[" + ", ".join(f"{x:.6g}" for x in v) + "]"
    with open(OUT, "w") as f:
        f.write(f"""// Generated by Scripts/train-key-model.py. Do not edit by hand.
// Trained on {len(entries)} tracks labelled by Mixed In Key; input: 72-band libKeyFinder chroma (C1–B6).
enum KeyModelWeights {{
    static let inputScale: Double = {SCALE}
    static let output: [[Double]] = [
        {row(W[0])},
        {row(W[1])},
    ]
    static let outputBias: [Double] = {row(b)}
}}
""")
    print(f"wrote {os.path.normpath(OUT)}")

if __name__ == "__main__":
    main()
